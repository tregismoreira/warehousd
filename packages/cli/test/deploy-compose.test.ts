import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { mkdtempSync, writeFileSync, readFileSync, rmSync, statSync, existsSync } from "node:fs";
import { loadConfig } from "@warehousd/broker";
import { renderComposeFile } from "../src/deploy/targets/compose";
import { targetFor } from "../src/deploy/targets";
import { ensureState, readState, stateDir } from "../src/state";
import { runDeploy } from "../src/deploy";

// Nothing in this target shells out. The mock is here so that "it ran no command at all" is
// assertable rather than assumed — a Compose deploy that quietly invoked docker would be this
// target's one unacceptable failure.
vi.mock("node:child_process");

// The destroy path reads a typed confirmation from stdin.
let promptAnswer = "";
vi.mock("node:readline/promises", () => ({
  createInterface: () => ({
    question: () => Promise.resolve(promptAnswer),
    close: () => undefined,
  }),
}));

const COMPOSE_FILE = "docker-compose.deploy.yml";
const ENV_FILE = join(".warehousd", "deploy.env");

function projectYaml(database: string): string {
  return `
project: test
deploy:
  target: compose
  app_name: test-app
  region: local
  image: ghcr.io/example/warehousd:1.2.3
  database:
${database}
collections:
  docs:
    description: Docs
    fields:
      title:
        type: text
        posture: allow
`;
}

